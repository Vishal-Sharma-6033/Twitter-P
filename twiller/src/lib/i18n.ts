export const getLanguageName = (language: LanguageCode) =>
  LANGUAGE_OPTIONS.find((option) => option.code === language)?.label || "English";

export const getLocaleForLanguage = (language: LanguageCode) =>
  LANGUAGE_LOCALES[language] || LANGUAGE_LOCALES.en;

export const translate = (
  language: LanguageCode,
  key: string,
  values: Record<string, string | number> = {}
) => {
  const template = translations[language]?.[key] || key;

  return Object.entries(values).reduce(
    (result, [placeholder, value]) => result.replaceAll(`{{${placeholder}}}`, String(value)),
    template
  );
};
